#!/usr/bin/env bash
#
# ship.sh — one command: publish a game update to BOTH mirrors.
#
#   ./ship.sh                     # auto commit message (timestamp)
#   ./ship.sh "tuned geometry dash"   # custom commit message
#
# No subcommands, no game name needed — it detects everything:
#   1. here.now  -> ./publish_herenow.sh  (also regenerates manifest.json)
#   2. GitHub    -> git add -A, commit, push to ai-games
#
# Safe to run when nothing changed: it will say "up to date" and skip the push.
#
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

HR=------------------------------------------------------------

# ------------------------------------------------------- 1) here.now -------
echo "$HR"
echo "  [1/2] here.now  (publish_herenow.sh)"
echo "$HR"
HERENOW_OK=1
if [[ -x "$SCRIPT_DIR/publish_herenow.sh" ]]; then
  "$SCRIPT_DIR/publish_herenow.sh" || { echo "  !! here.now publish failed (continuing to git)" >&2; HERENOW_OK=0; }
else
  echo "  !! publish_herenow.sh not found / not executable — skipping here.now" >&2
  HERENOW_OK=0
fi

# ----------------------------------------------- 2) GitHub (ai-games) -------
echo
echo "$HR"
echo "  [2/2] GitHub Pages  (commit + push to ai-games)"
echo "$HR"

# Manifest was already regenerated by publish_herenow.sh. If that path was
# skipped, regenerate it here so the committed manifest is never stale.
if [[ "$HERENOW_OK" -ne 1 && -f "$SCRIPT_DIR/update_manifest.py" ]]; then
  echo "  (here.now was skipped -> regenerating manifest.json locally)"
  python3 "$SCRIPT_DIR/update_manifest.py" >/dev/null
fi

git add -A
if git diff --cached --quiet; then
  echo "  Nothing to commit — already up to date. (No push.)"
else
  # Commit message: use what the user passed, else an auto timestamp.
  local_msg="${*:-}"
  if [[ -z "$local_msg" ]]; then
    local_msg="ship: update games $(date -u +%Y-%m-%d\ %H:%M\ UTC)"
  fi

  git -c commit.gpgsign=false commit -m "$local_msg" >/dev/null
  echo "  Committed: $local_msg"

  if GIT_TERMINAL_PROMPT=0 GIT_CONFIG_NOSYSTEM=1 git -c credential.helper=store push ai-games master; then
    echo "  Pushed to ai-games -> GitHub mirror -> Pages."
  else
    echo "  !! git push FAILED. Commit is saved locally; re-run ./ship.sh to push." >&2
  fi
fi

# ------------------------------------------------------------- summary ------
echo
echo "$HR"
echo "  DONE"
echo "    here.now      https://wistful-truffle-vpr4.here.now/"
echo "    GitHub Pages  https://wireddude.github.io/ai-games/"
echo "$HR"
